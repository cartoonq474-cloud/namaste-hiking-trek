function getSplinePath(points, includeM = true) {
  if (points.length === 0) return "";
  let d = includeM ? `M ${points[0].x},${points[0].y}` : `L ${points[0].x},${points[0].y}`;
  if (points.length === 1) return d;
  
  const tension = 0.15;
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[i - 1] || points[i];
    const p1 = points[i];
    const p2 = points[i + 1];
    const p3 = points[i + 2] || p2;
    
    const cpX1 = p1.x + (p2.x - p0.x) * tension;
    const cpY1 = p1.y + (p2.y - p0.y) * tension;
    
    const cpX2 = p2.x - (p3.x - p1.x) * tension;
    const cpY2 = p2.y - (p3.y - p1.y) * tension;
    
    d += ` C ${cpX1},${cpY1} ${cpX2},${cpY2} ${p2.x},${p2.y}`;
  }
  return d;
}

let localUnitState = 'm';

function getActiveUnit() {
  if (typeof window.getCurrentUnit === 'function') return window.getCurrentUnit();
  return localUnitState;
}

function setActiveUnit(unit) {
  localUnitState = unit;
  if (typeof window.setUnit === 'function') {
    window.setUnit(unit);
  } else {
    window.dispatchEvent(new Event('unitchange'));
  }
}

