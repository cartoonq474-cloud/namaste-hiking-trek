// Parse user content day by day
const days = [];
const dayBlocks = userContentRaw.split(/(?=Day \d+:)/g).filter(b => b.trim().length > 0);

dayBlocks.forEach(block => {
  const lines = block.trim().split('\n').map(l => l.trim()).filter(l => l.length > 0);
  const titleLine = lines[0]; // e.g. Day 1: Arrival at...
  const dayMatch = titleLine.match(/^Day (\d+):\s*(.*)$/);
  if (!dayMatch) return;
  const dayNum = parseInt(dayMatch[1]);
  const title = dayMatch[2];

  let lineIdx = 1;
  let subtitle = '';
  let flight = '';
  let trek = '';
  let distance = '';
  let dayHike = '';
  let acclimatizationHike = '';
  let accommodation = '';
  let meals = '';
  let overnight = '';
  let paragraphs = [];

  while (lineIdx < lines.length) {
    const line = lines[lineIdx];
    if (line.startsWith('Accommodation:')) {
      accommodation = line.replace('Accommodation:', '').trim();
    } else if (line.startsWith('Meals:')) {
      meals = line.replace('Meals:', '').trim();
    } else if (line.startsWith('Overnight:')) {
      overnight = line.replace('Overnight:', '').trim();
    } else if (line.startsWith('Flight:')) {
      flight = line.replace('Flight:', '').trim();
    } else if (line.startsWith('Trek:')) {
      trek = line.replace('Trek:', '').trim();
    } else if (line.startsWith('Distance:')) {
      distance = line.replace('Distance:', '').trim();
    } else if (line.startsWith('Day hike:')) {
      dayHike = line.replace('Day hike:', '').trim();
    } else if (line.startsWith('Acclimatization hike:')) {
      acclimatizationHike = line.replace('Acclimatization hike:', '').trim();
    } else if (!accommodation && !meals && !overnight && (line.includes('approximately') || line.includes('–') || line.includes('Departure from'))) {
      if (!subtitle) subtitle = line;
      else subtitle += ' | ' + line;
    } else {
      paragraphs.push(line);
    }
    lineIdx++;
  }

  days.push({
    dayNum,
    title,
    subtitle,
    flight,
    trek,
    distance,
    dayHike,
    acclimatizationHike,
    accommodation,
    meals,
    overnight,
    paragraphs
  });
});

